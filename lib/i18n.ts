export function getStatusLabel(status: IssueStatus, locale: Locale) {
  return copy[locale][statusKey[status]];
}

export function getPublicStatusLabel(status: PublicStatus, locale: Locale) {
  return copy[locale][publicStatusKey[status]];
}

export function getStatusGroupLabel(group: StatusGroup, locale: Locale) {
  return copy[locale][statusGroupKey[group]];
}

export function getCategoryLabel(category: Category, locale: Locale) {
  return copy[locale][categoryKey[category]];
}

export function formatCopy(template: string, vars: Record<string, string | number>) {
  return Object.entries(vars).reduce(
    (text, [key, value]) => text.replaceAll(`{${key}}`, String(value)),
    template,
  );
}

export function localizedField(
  item: Record<string, unknown>,
  locale: Locale,
  field: string,
): string {
  const suffix = locale === "hi" ? "Hi" : locale === "kn" ? "Kn" : "En";
  const value = item[`${field}${suffix}`];
  if (typeof value === "string" && value) return value;
  const fallback = item[`${field}En`];
  return typeof fallback === "string" ? fallback : "";
}
