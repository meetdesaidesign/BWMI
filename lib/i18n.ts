export type CopyKey = keyof typeof copy.en;
export const getCopy = (locale: Locale) => copy[locale];

const statusKey: Record<IssueStatus, CopyKey> = {
  reported: "statusSubmitted",
  acknowledged: "statusUnderReview",
  in_progress: "statusInProgress",
  awaiting_confirmation: "statusCheckFix",
  confirmed: "statusConfirmed",
  contested: "statusReopened",
};

const publicStatusKey: Record<PublicStatus, CopyKey> = {
  reported: "publicReported",
  verified: "publicVerified",
  assigned: "publicAssigned",
  in_progress: "publicInProgress",
  resolved: "publicResolved",
  reopened: "publicReopened",
};

const statusGroupKey: Record<StatusGroup, CopyKey> = {
  open: "statusOpen",
  in_progress: "statusGroupInProgress",
  resolved: "statusResolved",
};

const categoryKey: Record<Category, CopyKey> = {
  Roads: "categoryRoads",
  Waste: "categoryWaste",
  Water: "categoryWater",
  Lighting: "categoryLighting",
  Drainage: "categoryDrainage",
  Traffic: "categoryTraffic",
  Parks: "categoryParks",
  Other: "categoryOther",
};

export function getStatusLabel(status: IssueStatus, locale: Locale) {
  return copy[locale][statusKey[status]];
}

export function getPublicStatusLabel(status: PublicStatus, locale: Locale) {
  return copy[locale][publicStatusKey[status]];
}

export function getStatusGroupLabel(group: StatusGroup, locale: Locale) {
  return copy[locale][statusGroupKey[group]];
}

export function getCategoryLabel(category: Category, locale: Locale) {
  return copy[locale][categoryKey[category]];
}

export function formatCopy(template: string, vars: Record<string, string | number>) {
  return Object.entries(vars).reduce(
    (text, [key, value]) => text.replaceAll(`{${key}}`, String(value)),
    template,
  );
}

export function countCopy(count: number, one: string, many: string) {
  return formatCopy(count === 1 ? one : many, { count });
}

export function localizedField(
  item: Record<string, unknown>,
  locale: Locale,
  field: string,
): string {
  const suffix = locale === "hi" ? "Hi" : locale === "kn" ? "Kn" : "En";
  const value = item[`${field}${suffix}`];
  if (typeof value === "string" && value) return value;
  const fallback = item[`${field}En`];
  return typeof fallback === "string" ? fallback : "";
}
