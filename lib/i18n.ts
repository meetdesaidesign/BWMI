export type CopyKey = keyof typeof copy.en;
export const getCopy = (locale: Locale) => copy[locale];

const statusKey: Record<IssueStatus, CopyKey> = {
  reported: "statusSubmitted",
  acknowledged: "statusUnderReview",
  in_progress: "statusInProgress",
  awaiting_confirmation: "statusCheckFix",
  confirmed: "statusConfirmed",
  contested: "statusReopened",
};

export function getStatusLabel(status: IssueStatus, locale: Locale) {
  return copy[locale][statusKey[status]];
}

export function formatCopy(template: string, vars: Record<string, string | number>) {
  return Object.entries(vars).reduce(
    (text, [key, value]) => text.replaceAll(`{${key}}`, String(value)),
    template,
  );
}
